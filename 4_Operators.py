
# Arithmetic Operators

num_1 = 20
num_2 = 10

# Addition
sum = num_1 + num_2
print("Sum = ", sum)

# Likewise Subtraction, Multiplication, Division

# Exponent
exp = num_2 ** num_1
print("Exponent", exp)

# Modulo
mod = num_1 % num_2
print("remainder = ", mod)

# Assignment Operator

a = 5
print(a)

a += 5
print(a)


# Comparision Operators
a = 5
b = 10

print(a == b) # equal to comparision operators
print(a != b) # not equal to comparision operators

print(a > b) # greater than


# Logical operators

a = 10
print(a > 20 and a > 5) 
print(a > 20 or a > 5)
print(not(a > 20 or a > 5))


# Identity Operators

x = 5
y = 5
print(x is y)

z = 10
print(x is z)

print(x is not z)


# Memebership opertor

a = 5
b = 10

c = [1,2,3,4,5]

print(a in c)
print(b in c)
print(a not in c)










